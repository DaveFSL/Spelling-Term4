build("in", "revers", "ible");
check(/changes to <b>ir-<\/b>/.test($("#labFix").innerHTML) && d.activeElement === $("#labFix"), "in- + r root → ir- rule clue and focus");
build("", "revers", "able");
check(/-ible/.test($("#labFix").textContent), "-able on revers → -ible clue");
