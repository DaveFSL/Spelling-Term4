const part = (row, v) => $$(row + " .part").find(b => b.dataset.val === v);
check($("#testBtn").disabled, "Test locked until a root is chosen");
check($$("#targets .tw").every(t => t.textContent === "? ? ?"), "target words hidden (clues only) before building");
